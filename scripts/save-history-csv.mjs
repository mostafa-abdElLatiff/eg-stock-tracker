#!/usr/bin/env node
// Converts a stockanalysis.com /history/ table (copied as page text) into the
// exact CSV format the user's own investing.com exports use, and writes it to
// price-history/. Added Sept 8 2026, once it was established that a full year
// of daily OHLCV is self-servable (see CLAUDE.md's research-sources section:
// set BOTH the period dropdown to "1 Year" AND the rows dropdown to 500).
//
// Format target, matching the existing files byte-for-byte:
//   "Date","Price","Open","High","Low","Vol.","Change %"
//   "09/07/2026","120.80","118.99","122.90","118.51","3.34M","2.20%"
// - Date is MM/DD/YYYY, rows ordered NEWEST FIRST
// - Price is the raw Close (never Adj. Close - dividend adjustment would
//   distort support/resistance levels)
// - Volume uses M/K suffixes
//
// Usage: node scripts/save-history-csv.mjs <rawTextFile> "<Company Name>"
import { readFileSync, writeFileSync } from "fs";

const MONTHS = { Jan:"01", Feb:"02", Mar:"03", Apr:"04", May:"05", Jun:"06",
                 Jul:"07", Aug:"08", Sep:"09", Oct:"10", Nov:"11", Dec:"12" };

export function parseStockAnalysis(raw) {
  const rows = [];
  // Each data line: "Sep 6, 2026 115.99 118.20 115.00 118.20 118.20 1.91% 1,881,469"
  // Columns:         Date        Open   High   Low    Close  AdjClose Change Volume
  const re = /^([A-Z][a-z]{2}) (\d{1,2}), (\d{4})\s+([\d.,]+)\s+([\d.,]+)\s+([\d.,]+)\s+([\d.,]+)\s+([\d.,]+)\s+(-?[\d.]+%|-)\s+([\d,]+)$/;
  for (const line of raw.split(/\r?\n/)) {
    const m = line.trim().match(re);
    if (!m) continue;
    const [, mon, day, year, open, high, low, close, _adj, chg, vol] = m;
    rows.push({
      date: `${MONTHS[mon]}/${day.padStart(2, "0")}/${year}`,
      close: close.replace(/,/g, ""),
      open: open.replace(/,/g, ""),
      high: high.replace(/,/g, ""),
      low: low.replace(/,/g, ""),
      volume: Number(vol.replace(/,/g, "")),
      change: chg === "-" ? "0.00%" : chg,   // stockanalysis shows "-" for a flat day
    });
  }
  return rows;
}

// Match the source files' volume style: 3.34M / 727.38K / plain integer.
export function fmtVolume(v) {
  if (v >= 1e6) return (v / 1e6).toFixed(2) + "M";
  if (v >= 1e3) return (v / 1e3).toFixed(2) + "K";
  return String(v);
}

export function toCsv(rows) {
  const header = `"Date","Price","Open","High","Low","Vol.","Change %"`;
  const body = rows.map(r =>
    `"${r.date}","${r.close}","${r.open}","${r.high}","${r.low}","${fmtVolume(r.volume)}","${r.change}"`
  );
  return [header, ...body].join("\n") + "\n";
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const [rawFile, company] = process.argv.slice(2);
  if (!rawFile || !company) {
    console.error('Usage: node scripts/save-history-csv.mjs <rawTextFile> "<Company Name>"');
    process.exit(1);
  }
  const rows = parseStockAnalysis(readFileSync(rawFile, "utf8"));
  if (!rows.length) { console.error("No data rows parsed - check the input format."); process.exit(1); }
  const out = `/Users/mostafaabdellatif/Desktop/Projects/eg-stock/price-history/${company} Stock Price History.csv`;
  writeFileSync(out, toCsv(rows));
  console.log(`Wrote ${rows.length} rows -> ${out}`);
  console.log(`Range: ${rows[rows.length-1].date} .. ${rows[0].date}`);
}

